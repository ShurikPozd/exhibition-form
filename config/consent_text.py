"""Текст согласия на обработку персональных данных и его версия.

Реквизиты оператора берутся из переменных окружения (settings.py): обработкой
данных занимается заказчик, а не это приложение. ВЕРСИЯ меняется при правке текста —
она сохраняется вместе с каждой заявкой, чтобы было видно, на каких условиях человек
дал согласие.

Чтобы убрать согласие из формы, удалите поле с type == CONSENT из
config/form_fields.py: форма, валидация и выгрузка собираются из описания полей,
править больше нигде не нужно.
"""

from config.form_fields import CONSENT

CONSENT_VERSION = "2026-10-05"


def consent_text(
    operator_name: str, operator_email: str = "", operator_address: str = ""
) -> str:
    """Собирает текст согласия с реквизитами оператора персональных данных.

    Args:
        operator_name: наименование или ФИО оператора.
        operator_email: почта для отзыва согласия (необязательно).
        operator_address: адрес хранения данных (необязательно).

    Returns:
        str: текст согласия для показа под чекбоксом.
    """
    parts = [
        f"Отправляя форму, я подтверждаю, что ознакомлен(-а) с условиями обработки "
        f"персональных данных {operator_name} и даю согласие на обработку указанных "
        f"мной данных (имя, компания, телефон, адрес электронной почты) для целей "
        f"обработки заявок на выставке и связи по ним.",
        "Данные обрабатываются только для этих целей и не передаются третьим лицам, "
        "кроме случаев, предусмотренных законодательством.",
    ]
    if operator_address:
        parts.append(f"Данные хранятся по адресу: {operator_address}.")
    if operator_email:
        parts.append(
            f"Согласие можно отозвать письменным обращением на {operator_email}."
        )
    return " ".join(parts)


__all__ = ["CONSENT", "CONSENT_VERSION", "consent_text"]
